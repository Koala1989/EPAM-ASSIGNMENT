"""Slice InvenTree's OpenAPI schema down to the Parts API.

Downloads the schema from a running instance (or reads a saved copy),
keeps only the Parts paths plus the related routes the API tests need,
and every component schema they reference, directly or indirectly.
Writes requirements/openapi-parts.yaml with a provenance header.

Usage (needs PyYAML; the tools venv has it):
    tools/rag/.venv/Scripts/python.exe tools/slice_schema.py [--source <url or file>]

The default source is <base URL>/api/schema/: $INVENTREE_URL if set, else the baseURL of
automation/shared/environments/<TEST_ENV>.json (TEST_ENV defaults to local), the same
configuration the test suites use. The schema endpoint needs no login.
"""

import argparse
import json
import os
import sys
import urllib.request
from datetime import date
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = REPO_ROOT / "requirements" / "openapi-parts.yaml"

PATH_PREFIXES = ("/api/part/",)
EXTRA_PATHS = (
    "/api/company/part/",
    "/api/company/part/{id}/",
    "/api/stock/location/",
    "/api/stock/location/{id}/",
    "/api/user/me/token/",
)


def load(source: str) -> tuple[dict, str]:
    if source.startswith(("http://", "https://")):
        with urllib.request.urlopen(source) as response:
            return yaml.safe_load(response.read().decode("utf-8")), source
    return yaml.safe_load(Path(source).read_text(encoding="utf-8")), source


def refs(node):
    """Yield every $ref string found anywhere in node."""
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str):
                yield value
            else:
                yield from refs(value)
    elif isinstance(node, list):
        for item in node:
            yield from refs(item)


def main():
    environment = Path(__file__).resolve().parents[1] / "automation" / "shared" / "environments" / f"{os.environ.get('TEST_ENV') or 'local'}.json"
    base = os.environ.get("INVENTREE_URL") or json.loads(environment.read_text(encoding="utf-8"))["baseURL"]
    default = base.rstrip("/") + "/api/schema/"
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", default=default, help="schema URL or saved file")
    args = parser.parse_args()

    schema, source = load(args.source)
    all_paths = schema["paths"]
    keep = {p: v for p, v in all_paths.items() if p.startswith(PATH_PREFIXES) or p in EXTRA_PATHS}
    missing = [p for p in EXTRA_PATHS if p not in all_paths]
    if missing:
        sys.exit(f"Paths not in the schema: {missing}")

    components = schema.get("components", {})
    needed: dict[str, set] = {}
    queue = list(refs(keep))
    while queue:
        ref = queue.pop()
        _, _, section, name = ref.split("/", 3)
        if name in needed.setdefault(section, set()):
            continue
        needed[section].add(name)
        queue.extend(refs(components[section][name]))

    sliced_components = {
        section: {name: components[section][name] for name in sorted(names)}
        for section, names in sorted(needed.items())
    }
    if "securitySchemes" in components:
        sliced_components["securitySchemes"] = components["securitySchemes"]

    sliced = {
        "openapi": schema["openapi"],
        "info": schema["info"],
        "paths": dict(sorted(keep.items())),
        "components": sliced_components,
    }

    operations = sum(1 for v in keep.values() for k in v if k in ("get", "post", "put", "patch", "delete"))
    header = (
        f"# Parts slice of the InvenTree OpenAPI schema.\n"
        f"# Source: {source} ({schema['info']['title']} {schema['info']['version']}), sliced {date.today()}.\n"
        f"# Kept: paths starting with {', '.join(PATH_PREFIXES)}, plus {', '.join(EXTRA_PATHS)};\n"
        f"# every component they reference (transitively), and the security schemes.\n"
        f"# {len(keep)} paths, {operations} operations, "
        f"{sum(len(n) for n in needed.values())} components. Generated by tools/slice_schema.py; do not edit.\n"
    )
    OUTPUT.write_text(header + yaml.safe_dump(sliced, sort_keys=False, allow_unicode=True, width=120),
                      encoding="utf-8")
    print(f"Wrote {OUTPUT}: {len(keep)} paths, {operations} operations, "
          f"{sum(len(n) for n in needed.values())} components.")


if __name__ == "__main__":
    main()
